import assert from "node:assert/strict";
import { parseLineaEnlace, proponerOrganizacion } from "../js/organizacion.js";
import { parseNivel, camposDeCancion, estrellas, filaACancion } from "../js/repertorio.js";

assert.equal(parseNivel("").nivel, null);
assert.equal(parseNivel("0").nivel, 0);
assert.equal(parseNivel("3").nivel, 3);
assert.equal(parseNivel("★★★☆☆").nivel, 3);
assert.equal(parseNivel("texto inválido").nivel, null);
assert.equal(estrellas(null), "Por evaluar");
assert.equal(camposDeCancion({ titulo: "Prueba", cancion: { nivel: null }, enlaces: [] }).nivel, "por-evaluar");
assert.equal(filaACancion({ "Nombre de la canción": "Prueba", Nivel: "", _fila: 2 }).data.nivel, "por-evaluar");
assert.deepEqual(parseLineaEnlace("Título | subtítulo | https://example.com/?a=1|2"), { titulo: "Título | subtítulo", url: "https://example.com/?a=1|2" });
const fuente = { attachments: [{ name: "Título | subtítulo", url: "https://example.com/video" }] };
const recurso = { titulo: "Ejercicio", nivel: "inicial", cancion: { nivel: 0 }, etiquetas: ["nivel-0"], origenImportacion: { registros: [{ campos: {} }] }, enlaces: [{ titulo: "Título", url: "subtítulo" }] };
const patch = proponerOrganizacion(recurso, fuente);
assert.equal(patch.nivel, "por-evaluar");
assert.equal(patch.cancion.nivel, null);
assert.equal(patch.enlaces[0].url, fuente.attachments[0].url);
assert.equal(patch.estado, undefined);
assert.equal(patch.publico, undefined);
assert.equal(patch.titulo, undefined);
assert.deepEqual(proponerOrganizacion({ ...recurso, ...patch }, fuente), {});
const conNivelReal = { ...recurso, origenImportacion: { registros: [{ campos: { Nivel: "0" } }] } };
assert.equal(proponerOrganizacion(conNivelReal, fuente).nivel, undefined);
const actualizado = { ...recurso, ...patch, titulo: "Escalas mayores" };
assert.ok(proponerOrganizacion(actualizado, fuente).objetivos.includes("escalas"));
assert.equal(proponerOrganizacion({ titulo: "}" }).estado, "archivado");
console.log("PASS: nivel desconocido distinto de cero, enlaces con barras, fuentes recuperadas, publicación preservada, idempotencia y recatalogación al editar.");
